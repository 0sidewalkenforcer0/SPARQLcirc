"""Assemble reference/watdiv/RESULTS.md from the experiment CSVs produced by the overnight
run (E2 bench.csv, E3 e3_10M/e3_100M.csv, E4 e4_results.csv, E7 e7_results.csv). Robust to
missing files (a phase that didn't run is marked accordingly). Compares each result to the
pre-registered EVALUATION.md prediction. Run from reference/."""
import os, csv, datetime

HERE = os.path.dirname(os.path.abspath(__file__))
W = os.path.join(HERE, "watdiv")
def p(*a): return os.path.join(*a)

def read(path):
    if not os.path.exists(path):
        return None
    with open(path) as f:
        return list(csv.DictReader(f))

def table(rows, cols):
    if not rows:
        return "_(no data)_\n"
    out = ["| " + " | ".join(cols) + " |", "|" + "|".join("---" for _ in cols) + "|"]
    for r in rows:
        out.append("| " + " | ".join(str(r.get(c, "")) for c in cols) + " |")
    return "\n".join(out) + "\n"

def main():
    now = os.environ.get("RUN_STAMP", "")
    L = ["# SPARQL_circ - server evaluation results",
         f"\n_Generated by the overnight run{(' ' + now) if now else ''}. Datasets/engines: WatDiv 10M & 100M "
         "on GraphDB 10.7.6, d4 v1, PostgreSQL 18 + ProvSQL 1.11. All numbers from this server; "
         "compare against the pre-registered predictions in `EVALUATION.md`._\n"]

    # E3
    L.append("\n## E3 - construction scaling on an unmodified engine (GraphDB)\n")
    L.append("Bound (selective) S/L/F shapes; circuit built by the stock engine running our CONSTRUCT. "
             "`share` = T_string/T_circ (structural). *Predicted: near-linear build ~ small const x plain "
             "query; shallow-query compactness ~0.5-1x.*\n")
    for scale, fn in [("10M", "e3_10M.csv"), ("100M", "e3_100M.csv")]:
        rows = read(p(W, fn))
        L.append(f"\n**WatDiv {scale}**\n")
        L.append(table(rows, ["query", "bound", "status", "build_ms", "plain_ms", "c_overhead",
                              "deriv", "gates", "edges", "answers", "share"]) if rows
                 else "_(not run)_\n")

    # E4
    L.append("\n## E4 - compilation vs treewidth (d4 d-DNNF vs our OBDD)\n")
    L.append("Factored circuits over treewidth-controlled families; `obdd_size`/`ddnnf_nodes` are compiled "
             "sizes. *Predicted: bounded tw -> d-DNNF ~linear in n while OBDD is n^O(tw); growing tw -> both "
             "blow up. `obdd-timeout` = the pure-Python OBDD builder hit the wall where d4's d-DNNF kept "
             "compiling.*\n")
    e4 = read(p(W, "e4_results.csv"))
    L.append(table(e4, ["family", "name", "n_tokens", "tw", "status", "factored_gates",
                        "obdd_size", "ddnnf_nodes", "d4_wmc", "expected", "match"]) if e4 else "_(not run)_\n")

    # E7
    L.append("\n## E7 - head-to-head vs ProvSQL (exact PQE)\n")
    L.append("Same data + same per-triple probabilities + same query. *Predicted: identical exact probability "
             "(both knowledge-compile); our axis is deployability - ProvSQL needs a modified PostgreSQL, we run "
             "on a stock engine.*\n")
    e7 = read(p(W, "e7_results.csv"))
    L.append(table(e7, ["instance", "n_triples", "answers", "provsql_ms", "sparqlcirc_ms",
                        "circ_gates", "max_prob_diff", "match", "provsql_needs_engine_mod",
                        "ours_needs_engine_mod"]) if e7 else "_(not run)_\n")

    # E2 compactness
    L.append("\n## E2 - compactness: shared circuit vs per-answer strings\n")
    e2 = read(p(HERE, "bench.csv"))
    if e2:
        L.append("*Predicted: ~0.5-1x on shallow tree-like queries; ->10^2-10^3x on deep/recurring "
                 "(factored) families.*\n")
        L.append(table(e2, list(e2[0].keys())))
    else:
        L.append("_(not run)_\n")

    L.append("\n## Correctness (E1/E6) gate\n")
    L.append("`verify_gallery.py`, `verify_nonmono.py`, `verify_engine_paths.py`, `verify_engine_agnostic.py` "
             "run green before any scale numbers were trusted (see the overnight log). E4/E7 additionally "
             "cross-check d4/ProvSQL WMC == our OBDD == possible-world enumeration per instance.\n")

    out = p(W, "RESULTS.md")
    with open(out, "w") as f:
        f.write("\n".join(L))
    print(f"wrote {out}")

if __name__ == "__main__":
    main()
